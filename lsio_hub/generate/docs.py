"""
The documentation pages: one mkdocs page per image rendered by builder's docs template (the same template an
image repository's README comes from, with the mkdocs flavour), plus images-by-category.md.

Import: copy `images/` into the docs repository's `docs/images/` and `images-by-category.md` next to it.
"""

from __future__ import annotations

from builder.render import OUT_DIR, render_all

from .common import Files, GenerateContext, plain


def image_page(image_manifest: dict[str, object], ctx: GenerateContext) -> str:
    page: str = render_all(image_manifest, ctx.settings)[f"{OUT_DIR}/docs.md"]
    return page


def images_by_category(ctx: GenerateContext) -> str:
    by_category: dict[str, list[str]] = {}
    for image in ctx.current:
        for category in image.categories:
            by_category.setdefault(category, []).append(image.name)
    lines = [
        "---",
        "title: Images by category",
        "---",
        "<!-- Generated by the hub from every image.yml. Do not edit. -->",
        "# Images by category",
        "",
    ]
    names = {i.name: i for i in ctx.images}
    for category in sorted(by_category, key=str.casefold):
        lines += [f"## {category}", ""]
        for name in sorted(by_category[category]):
            image = names[name]
            lines.append(f"- [{image.title}](images/docker-{name}.md): {plain(image.summary_oneline)}")
        lines.append("")
    deprecated = [i for i in ctx.images if i.deprecated]
    if deprecated:
        lines += ["## Deprecated", ""]
        lines += [f"- [{i.title}](images/docker-{i.name}.md)" for i in deprecated]
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def generate(ctx: GenerateContext) -> Files:
    files: Files = {}
    for image in ctx.images:
        files[f"images/docker-{image.name}.md"] = image_page(image.manifest, ctx)
    files["images-by-category.md"] = images_by_category(ctx)
    return files
