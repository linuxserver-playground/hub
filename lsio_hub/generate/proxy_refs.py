"""
Reference reverse proxy configs for Caddy and Traefik from the manifest's `proxy` block, next to the SWAG
samples (`proxy.py`). They carry the same facts: the upstream container, port and scheme, the API paths that
stay open when authentication is switched on, the extra locations and the manifest's notes. Authentication is
offered as commented lines, as in the SWAG samples. Served in `/api/v1/catalog/<name>/proxy.json` as `caddy`
(a Caddyfile site block) and `traefik` (compose labels for the image's service).
"""

from __future__ import annotations

from typing import Any

from .common import ImageInput

Json = dict[str, Any]

DOMAIN = "example.com"


def _header(image: ImageInput, proxy: Json, tool: str, lines: list[str]) -> list[str]:
    out = [f"# {tool} reference config for {image.name}, generated by the hub from its image.yml."]
    out += [f"# {line}" for line in lines]
    out += [f"# {note}" for note in proxy.get("notes", [])]
    return out


def _caddy_upstream(indent: str, app: str, port: int, scheme: str) -> list[str]:
    if scheme != "https":
        return [f"{indent}reverse_proxy {app}:{port}"]
    return [
        f"{indent}reverse_proxy https://{app}:{port} {{",
        f"{indent}\ttransport http {{",
        f"{indent}\t\ttls_insecure_skip_verify",
        f"{indent}\t}}",
        f"{indent}}}",
    ]


def _caddy_auth(indent: str) -> list[str]:
    return [
        f"{indent}# Authentication: uncomment one.",
        f"{indent}# basic_auth {{",
        f"{indent}# \tuser <hash from `caddy hash-password`>",
        f"{indent}# }}",
        f"{indent}# forward_auth authelia:9091 {{",
        f"{indent}# \turi /api/authz/forward-auth",
        f"{indent}# \tcopy_headers Remote-User Remote-Groups Remote-Email Remote-Name",
        f"{indent}# }}",
        f"{indent}# forward_auth authentik-server:9000 {{",
        f"{indent}# \turi /outpost.goauthentik.io/auth/caddy",
        f"{indent}# \tcopy_headers X-Authentik-Username X-Authentik-Groups X-Authentik-Email X-Authentik-Name",
        f"{indent}# \ttrusted_proxies private_ranges",
        f"{indent}# }}",
    ]


def _caddy_routes(image: ImageInput, proxy: Json, indent: str, prefix: str) -> list[str]:
    app = image.rt["container_name"]
    port, scheme = int(proxy["port"]), str(proxy.get("scheme", "http"))
    lines: list[str] = []
    apis = [f"{prefix}{api}" for api in proxy.get("api_locations", [])]
    if apis:
        matchers = " ".join(f"{a} {a}/*" for a in apis)
        lines += [
            f"{indent}# API paths stay open so client applications keep working.",
            f"{indent}@api path {matchers}",
        ]
        lines += [f"{indent}handle @api {{", *_caddy_upstream(indent + "\t", app, port, scheme), f"{indent}}}", ""]
    for extra in proxy.get("extra_locations", []):
        path = f"{prefix}{extra['path'].rstrip('/')}"
        extra_port, extra_scheme = int(extra.get("port", port)), str(extra.get("scheme", scheme))
        lines += [f"{indent}handle {path}* {{"]
        if extra.get("auth", True):
            lines += [*_caddy_auth(indent + "\t"), ""]
        if extra.get("raw"):
            lines += [f"{indent}\t# The SWAG sample adds nginx directives here; see it for what they do."]
        lines += [*_caddy_upstream(indent + "\t", app, extra_port, extra_scheme), f"{indent}}}", ""]
    main = f"handle {prefix}* {{" if prefix else "handle {"
    lines += [f"{indent}{main}", *_caddy_auth(indent + "\t"), ""]
    lines += [*_caddy_upstream(indent + "\t", app, port, scheme), f"{indent}}}"]
    return lines


def caddy(image: ImageInput) -> str:
    proxy = image.manifest["proxy"]
    name, app = image.name, image.rt["container_name"]
    lines = _header(
        image,
        proxy,
        "Caddy",
        [
            f"Caddy and the {app} container share a docker network; replace {DOMAIN} with your domain.",
            "Caddy fetches the certificate and passes websockets through on its own.",
        ],
    )
    if proxy.get("subdomain", True):
        lines += ["", f"{name}.{DOMAIN} {{", *_caddy_routes(image, proxy, "\t", ""), "}"]
    folder = proxy.get("subfolder", {})
    if folder.get("supported", False):
        sub = [f"{DOMAIN} {{", *_caddy_routes(image, proxy, "\t", f"/{name}"), "}"]
        lines += [
            "",
            f"# Subfolder alternative, https://{DOMAIN}/{name}: set {name}'s base URL to /{name} first.",
            *([f"# {folder['base_url_note']}"] if folder.get("base_url_note") else []),
            *(sub if not proxy.get("subdomain", True) else [f"# {line}" if line else "#" for line in sub]),
        ]
    return "\n".join(lines) + "\n"


def traefik(image: ImageInput) -> str:
    proxy = image.manifest["proxy"]
    name, app = image.name, image.rt["container_name"]
    port, scheme = int(proxy["port"]), str(proxy.get("scheme", "http"))
    subdomain = proxy.get("subdomain", True)
    folder = proxy.get("subfolder", {})
    host = f"Host(`{name}.{DOMAIN}`)" if subdomain else f"Host(`{DOMAIN}`) && PathPrefix(`/{name}`)"
    prefix = "" if subdomain else f"/{name}"
    lines = _header(
        image,
        proxy,
        "Traefik",
        [
            f"Labels for the {name} service in your compose file. Traefik's docker provider must reach the {app}",
            "container on a shared network; the entrypoint websecure and the certificate resolver letsencrypt are",
            f"examples from a typical Traefik setup. Replace {DOMAIN} with your domain. Websockets need nothing extra.",
        ],
    )
    if not subdomain and folder.get("supported", False):
        lines += [
            f"# Set {name}'s base URL to /{name}."
            + (f" {folder['base_url_note']}" if folder.get("base_url_note") else "")
        ]
    labels = [
        "traefik.enable=true",
        f"traefik.http.services.{name}.loadbalancer.server.port={port}",
    ]
    if scheme == "https":
        labels += [
            f"traefik.http.services.{name}.loadbalancer.server.scheme=https",
            "# The app serves a self-signed certificate: define a serversTransport with insecureSkipVerify: true",
            "# in Traefik's file provider (named insecure here) and reference it.",
            f"traefik.http.services.{name}.loadbalancer.serverstransport=insecure@file",
        ]

    def router(key: str, rule: str, service: str, auth: bool, priority: int | None = None) -> list[str]:
        out = [
            f"traefik.http.routers.{key}.rule={rule}",
            f"traefik.http.routers.{key}.entrypoints=websecure",
            f"traefik.http.routers.{key}.tls.certresolver=letsencrypt",
            f"traefik.http.routers.{key}.service={service}",
        ]
        if priority is not None:
            out.append(f"traefik.http.routers.{key}.priority={priority}")
        if auth:
            out += [
                "# Authentication: uncomment one; the middleware is defined in your Traefik config.",
                f"# - traefik.http.routers.{key}.middlewares=authelia@docker",
                f"# - traefik.http.routers.{key}.middlewares=authentik@docker",
            ]
        return out

    labels += router(name, host, name, True)
    apis = [f"{prefix}{api}" for api in proxy.get("api_locations", [])]
    if apis:
        paths = " || ".join(f"PathPrefix(`{a}`)" for a in apis)
        labels += ["# API paths stay open so client applications keep working."]
        labels += router(f"{name}-api", f"{host} && ({paths})", name, False, 100)
    for i, extra in enumerate(proxy.get("extra_locations", []), start=1):
        key = f"{name}-extra{i}"
        service = name
        if int(extra.get("port", port)) != port:
            service = key
            labels += [f"traefik.http.services.{key}.loadbalancer.server.port={int(extra['port'])}"]
        rule = f"{host} && PathPrefix(`{prefix}{extra['path'].rstrip('/')}`)"
        labels += router(key, rule, service, bool(extra.get("auth", True)), 90)
    lines += ["services:", f"  {name}:", "    labels:"]
    lines += [f"      {label}" if label.startswith("#") else f"      - {label}" for label in labels]
    return "\n".join(lines) + "\n"
