"""
A Podman quadlet `.container` unit per image from `runtime`.

Import: copy `<name>.container` to `~/.config/containers/systemd/` (or `/etc/containers/systemd/`), run
`systemctl --user daemon-reload` and `systemctl --user start <name>`.
"""

from __future__ import annotations

from .common import Files, GenerateContext, ImageInput


def _quote(value: str) -> str:
    return f'"{value}"' if " " in value else value


def render(image: ImageInput) -> str:
    rt, name = image.rt, image.name
    lines = [
        f"# {name}.container: generated by the hub from {image.repo_url}/blob/{image.ctx['release_branch']}/image.yml",
        "# Optional parameters are commented out.",
        "",
        "[Unit]",
        f"Description={image.title} (LinuxServer.io)",
        "After=network-online.target",
        "Wants=network-online.target",
        "",
        "[Container]",
        f"Image={image.image_ref}",
        f"ContainerName={rt['container_name']}",
        "AutoUpdate=registry",
    ]

    def add(key: str, value: str, optional: bool) -> None:
        lines.append(f"{'# ' if optional else ''}{key}={value}")

    if rt["hostname"]:
        add("HostName", rt["hostname"]["value"], rt["hostname"]["optional"])
    if rt["network"]:
        add("Network", rt["network"]["mode"], rt["network"]["optional"])
    if rt["privileged"]:
        add("PodmanArgs", "--privileged", rt["privileged"] == "optional")
    for cap in rt["cap_add"]:
        add("AddCapability", cap["cap"], cap["optional"])
    for sec in rt["security_opt"]:
        add(
            "SecurityLabelDisable" if sec["run"].startswith("label=disable") else "PodmanArgs",
            "true" if sec["run"].startswith("label=disable") else f"--security-opt {sec['run']}",
            sec["optional"],
        )
    for env in image.env_items():
        add("Environment", _quote(f"{env['name']}={env['value']}"), env["optional"])
    for volume in rt["volumes"]:
        suffix = ":ro" if volume["mode"] == "ro" else ":Z"
        add("Volume", f"{volume['host_path']}:{volume['path']}{suffix}", volume["optional"])
    if not (rt["network"] and rt["network"]["mode"] == "host"):
        for port in rt["ports"]:
            add("PublishPort", f"{port['external']}:{port['internal']}", port["optional"])
    for device in rt["devices"]:
        add("AddDevice", f"{device['host_path']}:{device['path']}", device["optional"])
    if rt["mac_address"]:
        add("PodmanArgs", f"--mac-address={rt['mac_address']['value']}", rt["mac_address"]["optional"])
    for custom in rt["custom"]:
        if custom["flag"] == "shm-size":
            add("ShmSize", custom["values"][0], custom["optional"])
        elif custom["flag"] == "sysctl":
            for value in custom["values"]:
                add("Sysctl", value, custom["optional"])
        else:
            for value in custom["values"]:
                add("PodmanArgs", f"--{custom['flag']}={value}", custom["optional"])
    lines += ["", "[Service]", "Restart=always", "TimeoutStartSec=900", "", "[Install]", "WantedBy=default.target"]
    return "\n".join(lines) + "\n"


def generate(ctx: GenerateContext) -> Files:
    return {f"{i.name}.container": render(i) for i in ctx.current if i.manifest.get("publish", {}).get("quadlet", True)}
