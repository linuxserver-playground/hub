"""
An Arcane template registry: `registry.json` plus `<name>/compose.yaml` and `<name>/env.example` per image, in the
format of https://getarcane.app/docs/docker/template-registries (schema https://registry.getarcane.app/schema.json,
which rejects unknown fields).

The compose file is the image's recommended settings (what the docs' compose snippet shows without the `#optional`
lines) with host paths, ports and variables as `${VAR:-default}`, and env.example carries those values with their
descriptions, as Arcane's own templates do. `content_hash` is the SHA-256 of both files, which is how Arcane notices
an update. Template versions are semver as the schema demands; image versions are not, so every template is `1.0.0`
and the hash carries the change.

Import: Arcane > Customization > Templates > Add Registry > `<hub>/stores/arcane/registry.json`.
"""

from __future__ import annotations

import hashlib
import re
from typing import Any

from .common import Files, GenerateContext, ImageInput, category_slug, json_text, plain, yaml_text

Json = dict[str, Any]

SCHEMA = "https://registry.getarcane.app/schema.json"
ID_PATTERN = re.compile(r"^[a-z0-9-]+$")
TAG_PATTERN = re.compile(r"^[a-zA-Z0-9-]+$")
TEMPLATE_VERSION = "1.0.0"
COMMON_DEFAULTS = {"PUID": "1000", "PGID": "1000", "TZ": "Etc/UTC"}
COMMON_DESCRIPTIONS = {
    "PUID": "User ID the app runs as; `id your_user` on the host shows yours.",
    "PGID": "Group ID the app runs as; `id your_user` on the host shows yours.",
    "TZ": "Timezone, as a tz database name such as Europe/London.",
}
"""The README's wording points at sections further down it, which an env file does not have."""


def env_name(text: str) -> str:
    return re.sub(r"[^A-Z0-9]+", "_", text.upper()).strip("_")


def volume_var(path: str) -> str:
    """/config -> CONFIG_PATH, /data/media -> DATA_MEDIA_PATH."""
    return f"{env_name(path) or 'DATA'}_PATH"


def port_var(internal: str) -> str:
    """3001 -> PORT_3001, 53/udp -> PORT_53_UDP."""
    return f"PORT_{env_name(internal)}"


def _required(items: list[Json]) -> list[Json]:
    return [i for i in items if not i.get("optional", False)]


def template_files(image: ImageInput) -> tuple[str, str]:
    """(compose.yaml, env.example) for one image."""
    rt, name = image.rt, image.name
    env_lines: list[str] = [f"# {image.title} for Arcane, generated by the LinuxServer.io hub from image.yml.", ""]

    def variable(var: str, value: str, description: str) -> str:
        if description:
            env_lines.append(f"# {plain(description)}")
        env_lines.append(f"{var}={value}")
        env_lines.append("")
        return f"${{{var}:-{value}}}" if value else f"${{{var}}}"

    service: Json = {"image": image.image_ref, "container_name": rt["container_name"]}
    for key in ("hostname", "mac_address"):
        if rt.get(key) and not rt[key].get("optional", False):
            service[key] = rt[key]["value"]
    if rt["privileged"] is True:
        service["privileged"] = True
    if caps := [c["cap"] for c in _required(rt["cap_add"])]:
        service["cap_add"] = caps
    if secs := [s["compose"] for s in _required(rt["security_opt"])]:
        service["security_opt"] = secs
    if rt["network"] and not rt["network"].get("optional"):
        service["network_mode"] = rt["network"]["mode"]

    environment: Json = {}
    if rt["common_env"] is True:
        for item in rt["common_env_vars"]:
            value = COMMON_DEFAULTS.get(item["name"], item["value"])
            description = COMMON_DESCRIPTIONS.get(item["name"], item.get("description", ""))
            environment[item["name"]] = variable(item["name"], value, description)
    for item in _required(rt["env"]):
        value = "" if item.get("secret") else str(item["value"])
        environment[item["name"]] = variable(item["name"], value, item.get("description", ""))
    if environment:
        service["environment"] = environment

    volumes = []
    for v in _required(rt["volumes"]):
        host = variable(volume_var(v["path"]), f".{v['path']}", v.get("description", ""))
        volumes.append(f"{host}:{v['path']}" + (":ro" if v["mode"] == "ro" else ""))
    if volumes:
        service["volumes"] = volumes
    ports = []
    for p in _required(rt["ports"]):
        external = variable(port_var(p["internal"]), str(p["external"]).split("/")[0], p.get("description", ""))
        ports.append(f"{external}:{p['internal']}")
    if ports:
        service["ports"] = ports
    if devices := [f"{d['host_path']}:{d['path']}" for d in _required(rt["devices"])]:
        service["devices"] = devices
    for c in _required(rt["custom"]):
        service[c["compose"]] = list(c["values"]) if c["is_array"] else c["values"][0]
    service["restart"] = "unless-stopped"

    compose: Json = {
        "x-arcane": {"icon": image.logo, "urls": [u for u in (image.project_url, image.repo_url) if u]},
        "services": {name: service},
    }
    if not image.logo:
        compose["x-arcane"].pop("icon")
    return yaml_text(compose), "\n".join(env_lines).rstrip("\n") + "\n"


def tags(image: ImageInput) -> list[str]:
    found = ["linuxserver"]
    for category in image.categories:
        slug = category_slug(category)
        if TAG_PATTERN.match(slug) and slug not in found:
            found.append(slug)
    return found


def generate(ctx: GenerateContext) -> Files:
    root = f"{ctx.site.stores_root}/arcane"
    files: Files = {}
    templates: list[Json] = []
    for image in ctx.enabled("arcane"):
        if not ID_PATTERN.match(image.name):
            continue
        compose, env = template_files(image)
        files[f"{image.name}/compose.yaml"] = compose
        files[f"{image.name}/env.example"] = env
        template: Json = {
            "id": image.name,
            "name": image.title,
            "description": plain(image.summary_oneline),
            "version": TEMPLATE_VERSION,
            "author": "linuxserver.io",
            "compose_url": f"{root}/{image.name}/compose.yaml",
            "env_url": f"{root}/{image.name}/env.example",
            "documentation_url": f"{ctx.settings.site_url}/images/{image.name}/",
            "content_hash": hashlib.sha256((compose + env).encode()).hexdigest(),
            "tags": tags(image),
        }
        if image.logo:
            template["icon_url"] = image.logo
        templates.append(template)
    if templates:
        files["registry.json"] = json_text(
            {
                "$schema": SCHEMA,
                "name": "LinuxServer.io",
                "description": "Every LinuxServer.io image as an Arcane template, generated from its manifest.",
                "version": TEMPLATE_VERSION,
                "author": "linuxserver.io",
                "url": f"{ctx.settings.site_url}/stores/",
                "templates": templates,
            }
        )
    return files
