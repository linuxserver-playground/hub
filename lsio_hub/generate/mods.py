"""
The legacy `mod-list.yml` (images -> their mods, as linuxserver/docker-mods publishes it) rebuilt from
data/mods.json, for anything that still reads that shape.

Import: `https://<hub>/stores/mods/mod-list.yml`; the structured index is `/api/v1/mods.json`.
"""

from __future__ import annotations

from typing import Any

from .common import Files, GenerateContext, yaml_text

Json = dict[str, Any]


def mod_list(mods: list[Json]) -> Json:
    by_image: dict[str, dict[str, str]] = {}
    for mod in mods:
        if mod.get("deprecated"):
            continue
        for image in mod.get("applies_to") or [mod["target"]]:
            by_image.setdefault(image, {})[mod["name"]] = mod["url"]
    out: Json = {}
    for image in sorted(by_image):
        entries = by_image[image]
        out[image] = {
            "mod_count": len(entries),
            "container_mods": [{name: entries[name]} for name in sorted(entries)],
        }
    return {"mods": out}


def generate(ctx: GenerateContext) -> Files:
    mods = ctx.store.mods.get("mods", [])
    header = "# Generated by the hub from data/mods.json. Do not edit."
    return {"mod-list.yml": yaml_text(mod_list(mods), header=header)}
